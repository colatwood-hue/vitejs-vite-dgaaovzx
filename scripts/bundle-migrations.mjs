// Writes supabase/setup.sql: every migration in order, plus the bookkeeping rows that
// scripts/migrate.mjs uses, so pasting it into Supabase's SQL editor equals running `npm run db:migrate`.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const root = path.join(path.dirname(new URL(import.meta.url).pathname), '..')
const dir = path.join(root, 'supabase', 'migrations')
const files = (await readdir(dir)).filter((f) => f.endsWith('.sql')).sort()
let out = `-- The Dash: complete database setup for a NEW, empty Supabase project.\n-- Generated by scripts/bundle-migrations.mjs. Paste into Supabase > SQL Editor and click Run.\n\nbegin;\n\ncreate table if not exists _dash_migrations (name text primary key, applied_at timestamptz not null default now());\n`
for (const f of files) {
  out += `\n-- ── ${f} ──\n${await readFile(path.join(dir, f), 'utf8')}\ninsert into _dash_migrations (name) values ('${f}');\n`
}
out += `\nalter table _dash_migrations enable row level security;\n\ncommit;\n`
await writeFile(path.join(root, 'supabase', 'setup.sql'), out)
console.log(`wrote supabase/setup.sql (${files.length} migrations)`)
