/**
 * Binary storage for voice notes and issue images.
 *
 *   STORAGE_PROVIDER=db (default)  bytes live in Postgres (simplest; fine for small files)
 *   STORAGE_PROVIDER=s3            any S3-compatible store: AWS S3, Cloudflare R2, Backblaze B2, MinIO…
 *
 * With S3, the browser uploads directly to the bucket using a short-lived
 * presigned PUT URL, so large recordings never pass through the app server
 * (and Vercel's ~4.5 MB request-body limit doesn't apply).
 */
import { randomUUID } from "node:crypto";
import { DeleteObjectCommand, GetObjectCommand, HeadObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

export type UploadKind = "audio" | "image";

export const UPLOAD_LIMITS: Record<UploadKind, { maxBytes: number; types: RegExp }> = {
  audio: { maxBytes: 100 * 1024 * 1024, types: /^(audio\/[\w.+-]+|video\/(webm|mp4))$/ },
  image: { maxBytes: 10 * 1024 * 1024, types: /^image\/(jpeg|png|webp|gif)$/ },
};

const EXT: Record<string, string> = {
  "audio/webm": "webm", "video/webm": "webm", "audio/ogg": "ogg", "audio/mp4": "m4a", "video/mp4": "m4a",
  "audio/x-m4a": "m4a", "audio/aac": "aac", "audio/mpeg": "mp3", "audio/wav": "wav", "audio/x-wav": "wav",
  "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp", "image/gif": "gif",
};

export function storageProvider(): "db" | "s3" {
  return (process.env.STORAGE_PROVIDER ?? "db").toLowerCase() === "s3" ? "s3" : "db";
}

export function s3ConfigProblem(): string | null {
  if (storageProvider() !== "s3") return null;
  const missing = ["S3_BUCKET", "S3_ACCESS_KEY_ID", "S3_SECRET_ACCESS_KEY"].filter((k) => !process.env[k]);
  return missing.length ? `Missing ${missing.join(", ")}.` : null;
}

let client: S3Client | null = null;
function s3() {
  const problem = s3ConfigProblem();
  if (problem) throw new Error(`Object storage misconfigured: ${problem}`);
  client ??= new S3Client({
    region: process.env.S3_REGION || "auto",
    endpoint: process.env.S3_ENDPOINT || undefined,
    forcePathStyle: process.env.S3_FORCE_PATH_STYLE === "true",
    credentials: { accessKeyId: process.env.S3_ACCESS_KEY_ID!, secretAccessKey: process.env.S3_SECRET_ACCESS_KEY! },
  });
  return client;
}
const bucket = () => process.env.S3_BUCKET!;

/** Tests reset the cached client after changing env. */
export function resetStorageClientForTests() {
  client = null;
}

export function validateUpload(kind: UploadKind, mime: string, size: number): string | null {
  const lim = UPLOAD_LIMITS[kind];
  const base = mime.split(";")[0].trim().toLowerCase();
  if (!lim.types.test(base)) return kind === "audio" ? "That file isn't an audio file." : "Use JPEG, PNG, WebP or GIF.";
  if (!Number.isFinite(size) || size <= 0) return "The file is empty.";
  if (size > lim.maxBytes) return `File is larger than ${Math.round(lim.maxBytes / 1024 / 1024)} MB.`;
  return null;
}

export function newKey(kind: UploadKind, mime: string) {
  const base = mime.split(";")[0].trim().toLowerCase();
  return `${kind}/${new Date().toISOString().slice(0, 7)}/${randomUUID()}.${EXT[base] ?? "bin"}`;
}

/** Keys are only ever generated by newKey(); anything else is rejected. */
export function isValidKey(kind: UploadKind, key: string) {
  return new RegExp(`^${kind}/\\d{4}-\\d{2}/[0-9a-f-]{36}\\.[a-z0-9]{2,4}$`).test(key);
}

export async function presignUpload(kind: UploadKind, mime: string, size: number) {
  const problem = validateUpload(kind, mime, size);
  if (problem) throw new Error(problem);
  const key = newKey(kind, mime);
  const contentType = mime.split(";")[0].trim().toLowerCase();
  const url = await getSignedUrl(s3(), new PutObjectCommand({ Bucket: bucket(), Key: key, ContentType: contentType, ContentLength: size }), {
    expiresIn: 600,
  });
  return { key, url, headers: { "Content-Type": contentType } };
}

/** Confirms a direct upload landed and returns its real size/type (never trust the client). */
export async function statUpload(kind: UploadKind, key: string) {
  if (!isValidKey(kind, key)) throw new Error("Invalid upload key.");
  const head = await s3().send(new HeadObjectCommand({ Bucket: bucket(), Key: key }));
  const size = Number(head.ContentLength ?? 0);
  const mime = head.ContentType ?? "application/octet-stream";
  const problem = validateUpload(kind, mime, size);
  if (problem) {
    await s3().send(new DeleteObjectCommand({ Bucket: bucket(), Key: key }));
    throw new Error(problem);
  }
  return { size, mime };
}

export async function putObject(kind: UploadKind, data: Buffer, mime: string) {
  const key = newKey(kind, mime);
  await s3().send(new PutObjectCommand({ Bucket: bucket(), Key: key, Body: data, ContentType: mime.split(";")[0] }));
  return key;
}

export async function getObject(key: string): Promise<Buffer> {
  const res = await s3().send(new GetObjectCommand({ Bucket: bucket(), Key: key }));
  return Buffer.from(await res.Body!.transformToByteArray());
}

export async function presignDownload(key: string, seconds = 300) {
  return getSignedUrl(s3(), new GetObjectCommand({ Bucket: bucket(), Key: key }), { expiresIn: seconds });
}

/** Read an asset row's bytes wherever they live. */
export async function readAssetBytes(asset: { data: Buffer | null; storageKey: string | null }): Promise<Buffer> {
  if (asset.data) return asset.data;
  if (asset.storageKey) return getObject(asset.storageKey);
  throw new Error("Asset has no data.");
}
